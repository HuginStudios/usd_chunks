"""The hand-written docs point at symbols that exist.

A refactor that moves a class silently breaks every page linking to it, and nothing else in
this suite looks at the docs. That happened in this branch: ChunkParamWidgetBase and
ChunkWidgetFactoryBase moved to chunk_widget_api and SceneSender to chunk_scene, leaving
three dead cross-references in docs/plugins.md that only a docs build would have surfaced.

Resolution is checked the way mkdocstrings does it -- statically, by reading the source.
That distinction matters here: chunk_core re-exports SceneSender through a module
__getattr__, so the old path still works at runtime while the documentation link stays
broken. Importing and calling hasattr() would have passed and proved nothing.
"""
from __future__ import annotations

import ast
import importlib
import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent
DOCS = REPO / "docs"

#: `[Label][usd_chunks.module.Symbol]` -- an mkdocstrings cross-reference.
XREF = re.compile(r"\]\[(usd_chunks[\w\.]*)\]")
#: `::: usd_chunks.module` -- an mkdocstrings injection directive.
DIRECTIVE = re.compile(r"^:::\s+(usd_chunks[\w\.]*)\s*$", re.M)


def doc_pages():
    """Every hand-written page. docs/reference/ is generated by gen_ref_nav.py."""
    return sorted(p for p in DOCS.glob("*.md"))


def references():
    """(page, reference) for every mkdocstrings reference in the hand-written docs."""
    found = []
    for page in doc_pages():
        text = open(page, encoding="utf-8").read()
        for ref in XREF.findall(text) + DIRECTIVE.findall(text):
            found.append((page.relative_to(REPO).as_posix(), ref))
    return found


REFERENCES = references()


def defined_in_source(module, name: str) -> bool:
    """Is `name` defined at the top level of this module's own source?

    Static, like griffe. A name that only appears at runtime -- a re-export through
    __getattr__, or something injected by a decorator -- is not documentable at that path,
    so hasattr() is the wrong question.
    """
    tree = ast.parse(open(module.__file__, encoding="utf-8").read())
    for node in tree.body:
        if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            if node.name == name:
                return True
        elif isinstance(node, ast.Assign):
            if any(isinstance(t, ast.Name) and t.id == name for t in node.targets):
                return True
        elif isinstance(node, ast.AnnAssign):
            if isinstance(node.target, ast.Name) and node.target.id == name:
                return True
    return False


def resolve(ref: str) -> str:
    """"" if the reference resolves, else why it does not."""
    try:
        importlib.import_module(ref)
        return ""  # a whole module, e.g. `::: usd_chunks.chunk_core`
    except ImportError:
        pass
    module_path, _, name = ref.rpartition(".")
    if not module_path:
        return f"{ref!r} is not a module and has no parent to look in"
    try:
        module = importlib.import_module(module_path)
    except ImportError as exc:
        return f"module {module_path!r} does not import ({exc})"
    if not defined_in_source(module, name):
        return f"{name!r} is not defined in {module_path!r}"
    return ""


class TestDocReferences:
    def test_the_docs_contain_references_at_all(self):
        """Guards the parametrized test below: if the regex stops matching, every case
        vanishes and the file passes by finding nothing."""
        assert REFERENCES, "no mkdocstrings references found -- has the syntax changed?"

    @pytest.mark.parametrize("page,ref", REFERENCES,
                             ids=[f"{p}:{r}" for p, r in REFERENCES])
    def test_reference_resolves(self, page, ref):
        problem = resolve(ref)
        assert not problem, f"{page} links to {ref} but {problem}"


class TestTheCheckWorks:
    def test_a_moved_symbol_is_detected(self):
        """The failure this file exists for: a class that used to live somewhere else."""
        assert resolve("usd_chunks.chunk_core.ChunkParamWidgetBase")

    def test_a_runtime_only_re_export_does_not_count(self):
        """chunk_core re-exports SceneSender via module __getattr__, so it resolves at
        runtime and is still undocumentable at that path. If this ever starts passing,
        the check has quietly become a hasattr() and stops catching moves."""
        import usd_chunks.chunk_core as core

        assert core.SceneSender is not None, "the runtime re-export is gone; update this test"
        assert resolve("usd_chunks.chunk_core.SceneSender")

    def test_a_real_symbol_resolves(self):
        assert not resolve("usd_chunks.chunk_scene.SceneSender")

    def test_a_whole_module_resolves(self):
        assert not resolve("usd_chunks.chunk_core")
