"""Duplicate Prim's destination path.

An empty field is filled in with a free path. A field that is already set is uniqued too,
so a chunk cannot be pointed at a prim something else has already made -- it steps aside
to the next free suffix instead.

This reverses #171, which removed that uniquing. #171 was written for a real symptom: a
saved scene reopened with FlowerPotA_5_copy1 turned into FlowerPotA_5_copy, and a Transform
aimed at the old path was left pointing at a prim that no longer existed. The explanation
offered at the time -- that saving bakes the copy into the file, so on reopen the chunk
mistakes its own past output for a stranger's prim -- does not hold: save_scene writes the
chunk graph only, and content is regenerated by re-running chunks. Neither the reported
file nor a rebuilt version of it reproduces the rename, with or without the removed check.

So the symptom was real and the cause is still unknown. Uniquing is back because it is
what the chunk should do, and because a path being silently occupied by another chunk is
the more common problem in practice. If the rename reappears, execute()'s else branch is
where to look, and the missing piece is something usdview does that a headless load does
not -- extra cook passes from the graph, gizmos or debounced recooks.

get_unique_path is given the PARAM, not its value: that way it clears this chunk's own
layer before checking, so the copy it made last cook does not read as a collision and walk
the suffix up on every execute.
"""
from __future__ import annotations

import pytest
from pxr import Usd, UsdGeom

from usd_chunks import chunk_registry
from usd_chunks.chunk_core import SceneSender
from usd_chunks.chunk_stage import initialize as _chunk_usd_init, save_scene


class _DummyScene(SceneSender):
    def get_stage(self):
        return None

    def get_selected_prims(self):
        return []


def _scene_for(stage):
    class _StageScene(_DummyScene):
        def get_stage(self):
            return stage

    s = _StageScene()
    chunk_registry.ChunkRegistry().initialize(s, "pytest")
    chunk_registry.ChunkLayerManager().reset()
    chunk_registry.ChunkLayerManager().initialize(stage)
    _chunk_usd_init(stage, s)
    return s


def _mk(scene, key):
    mod = chunk_registry.ChunkRegistry().get_chunk_module(key)
    cs = mod.create() if mod.loaded else mod.load()
    for c in cs:
        scene.add_chunk(c)
    return cs[0]


SOURCE = "/Kitchen_set/Props_grp/FlowerPotA_5"
CHOSEN_DEST = SOURCE + "_copy1"


@pytest.fixture
def reopened(qapp, tmp_path):
    """A Duplicate Prim whose destination the user set by hand, saved and reopened."""
    stage = Usd.Stage.CreateInMemory()
    UsdGeom.Xform.Define(stage, SOURCE)
    scene = _scene_for(stage)

    dup = _mk(scene, "duplicate_prim")
    dup.get_param("source_prim").set_prims([stage.GetPrimAtPath(SOURCE)])
    qapp.processEvents()

    # What the user ends up with when _copy is already taken. Set explicitly so the test
    # does not depend on how the suggestion happened to be reached.
    dup.get_param("dest_path").value = CHOSEN_DEST
    qapp.processEvents()

    out = tmp_path / "dup.usda"
    save_scene(scene, out)
    saved_text = out.read_text(encoding="utf-8")

    stage2 = Usd.Stage.Open(str(out))
    # The scene file carries the geometry as well as the graph: the source prim, and the
    # duplicate the chunk baked on the way out. Without that baked prim on the stage there
    # is nothing for the old collision check to trip over, and the bug does not reproduce.
    UsdGeom.Xform.Define(stage2, SOURCE)
    UsdGeom.Xform.Define(stage2, CHOSEN_DEST)
    scene2 = _scene_for(stage2)
    qapp.processEvents()
    return scene2, saved_text


def test_the_saved_file_holds_the_chosen_destination(reopened):
    """Pinned so a fix cannot drift to the save side, which was never wrong."""
    _scene2, saved_text = reopened

    assert CHOSEN_DEST in saved_text, "the file should record the destination the user set"






def test_an_empty_destination_is_still_filled_in_and_still_avoids_what_is_there(qapp):
    """The suggestion still works, and still steps around an occupied path."""
    stage = Usd.Stage.CreateInMemory()
    UsdGeom.Xform.Define(stage, SOURCE)
    UsdGeom.Xform.Define(stage, SOURCE + "_copy")   # the obvious name is taken
    scene = _scene_for(stage)

    dup = _mk(scene, "duplicate_prim")
    dup.get_param("source_prim").set_prims([stage.GetPrimAtPath(SOURCE)])
    qapp.processEvents()

    dest = dup.get_param("dest_path").value
    assert dest and dest != SOURCE + "_copy", (
        f"an empty destination should be filled with a free path, got {dest!r}"
    )
